"""64K single-entry exact-token-prefix inference adapter."""
from dataclasses import dataclass
import gc, hashlib, json, math, re, threading, time, uuid
from pathlib import Path

class CacheRuntimeError(Exception):
    def __init__(self,status,code,message):
        super().__init__(message)
        self.status,self.code=status,code

@dataclass
class CacheEntry:
    owner:str
    session_id:str
    revision:int
    epoch:int
    dependency_digest:str
    fingerprint:str
    token_ids:list
    cache:object
    next_logits:object
    created_at:float
    last_used:float
    bytes_by_device:dict

class CacheRuntime:
    def __init__(self,legacy_backend,policy,runtime_dir):
        self.backend=legacy_backend
        self.model,self.tokenizer,self.torch=legacy_backend.model,legacy_backend.tokenizer,legacy_backend.torch
        self.device=legacy_backend.device
        self.policy=policy
        self.runtime_dir=Path(runtime_dir)
        self._entry=self._inflight=None
        self._last_reason="empty"
        self._planner_profile=None
        self._state_lock=threading.RLock()
        identity={"model":legacy_backend.config,"adapter":getattr(legacy_backend,"adapter_sha256",""),
                  "template":getattr(self.tokenizer,"chat_template",""),"policy":policy["policy_id"],
                  "runtime_code":hashlib.sha256(Path(__file__).read_bytes()).hexdigest()}
        self.fingerprint=hashlib.sha256(json.dumps(identity,sort_keys=True,default=str).encode()).hexdigest()
        self.process_epoch=time.time_ns()
        self._eos=set()
        opts=legacy_backend.generation_config(max_new_tokens=1)
        for value in [opts.get("eos_token_id"),getattr(self.tokenizer,"eos_token_id",None),
                      getattr(self.model.generation_config,"eos_token_id",None)]:
            if value is not None:
                self._eos.update(value if isinstance(value,(list,tuple)) else [value])

    def encode(self,messages):
        if not isinstance(messages,list) or not messages or len(messages)>128:
            raise CacheRuntimeError(422,"messages_limit","Messages must contain 1 to 128 entries")
        if len(json.dumps(messages,ensure_ascii=False).encode())>8388608:
            raise CacheRuntimeError(422,"body_limit","Assembled context exceeds 8MiB")
        for m in messages:
            if not isinstance(m,dict) or m.get("role") not in {"system","user","assistant"} or not isinstance(m.get("content"),str):
                raise CacheRuntimeError(400,"invalid_messages","Invalid message")
            pattern=getattr(self.backend,"control_pattern",None)
            if pattern and pattern.search(m["content"]):
                raise CacheRuntimeError(400,"control_tokens","Literal model control tokens are not allowed")
        # Gemma's generation prompt includes an empty thought channel, while its
        # history template omits it and trims assistant whitespace. Retain both
        # server-generated bytes so a subsequent turn has the consumed prefix.
        rendered=[]
        replacements={}
        nonce=uuid.uuid4().hex
        while any(nonce in m["content"] for m in messages):nonce=uuid.uuid4().hex
        for i,m in enumerate(messages):
            item=dict(m)
            if m["role"]=="assistant":
                marker="__active_cache_"+nonce+"_"+str(i)+"__"
                replacements[marker]=m["content"]
                item["content"]=marker
            rendered.append(item)
        prompt=self.tokenizer.apply_chat_template(rendered,tokenize=False,add_generation_prompt=True,enable_thinking=False)
        header="<|turn>model\n"
        channel="<|channel>thought\n<channel|>"
        if prompt.endswith(header+channel):
            prompt=re.sub(re.escape(header)+"(?!"+re.escape(channel)+")",
                          lambda _:header+channel,prompt)
        for marker,content in replacements.items():
            if prompt.count(marker)!=1:
                raise CacheRuntimeError(500,"template_contract","Assistant template placeholder mismatch")
            prompt=prompt.replace(marker,content)
        return list(self.tokenizer(prompt,add_special_tokens=False,truncation=False)["input_ids"])

    def _limits(self,ids,output,temperature,top_p):
        limits=self.policy["token_limits"]
        if type(output) is not int or not 1<=output<=limits["output_hard_cap"]:
            raise CacheRuntimeError(422,"output_budget_exceeded","Output must be between 1 and 4096")
        if not ids or len(ids)>limits["rendered_input_hard_cap"] or len(ids)+output>limits["request_total_hard_cap"]:
            raise CacheRuntimeError(422,"context_budget_exceeded","Rendered input exceeds the 64K budget")
        if isinstance(temperature,bool) or not isinstance(temperature,(int,float)) or not math.isfinite(temperature) or not 0<=temperature<=2:
            raise CacheRuntimeError(400,"invalid_temperature","Invalid temperature")
        if isinstance(top_p,bool) or not isinstance(top_p,(int,float)) or not math.isfinite(top_p) or not 0<top_p<=1:
            raise CacheRuntimeError(400,"invalid_top_p","Invalid top_p")

    def _expired(self,entry,now):
        p=self.policy["kv_cache"]
        return now-entry.last_used>=p["idle_ttl_seconds"] or now-entry.created_at>=p["absolute_ttl_seconds"]

    def _clear(self,reason):
        self._entry=self._inflight=None
        self._last_reason=reason

    def evict(self,owner=None,session_id=None,reason="invalidated"):
        with self._state_lock:
            for entry in [self._entry,self._inflight]:
                if entry and (owner is None or owner==entry.owner) and (session_id is None or session_id==entry.session_id):
                    self._clear(reason)
                    break

    def abort(self):
        with self._state_lock:
            self._clear("failed_or_cancelled")

    def _stats(self,reset=False):
        t=self.torch
        if not t.cuda.is_available():return {}
        data={}
        for d in range(t.cuda.device_count()):
            if reset:t.cuda.reset_peak_memory_stats(d)
            free,total=t.cuda.mem_get_info(d)
            reserved=t.cuda.memory_reserved(d)
            data[str(d)]={"allocated":t.cuda.memory_allocated(d),"reserved":reserved,
                          "peak":t.cuda.max_memory_allocated(d),"free":free,"total":total,
                          "usable":min(total,free+reserved)}
        return data

    def _sync(self):
        if self.torch.cuda.is_available():
            for d in range(self.torch.cuda.device_count()):self.torch.cuda.synchronize(d)

    def _unique_bytes(self,cache):
        totals,seen={},set()
        for layer in getattr(cache,"layers",[]):
            for name in ["keys","values"]:
                tensor=getattr(layer,name,None)
                if tensor is None:continue
                storage=tensor.untyped_storage()
                signature=(str(tensor.device),storage.data_ptr())
                if signature in seen:continue
                seen.add(signature)
                device=str(tensor.device.index) if tensor.device.type=="cuda" else "cpu"
                totals[device]=totals.get(device,0)+storage.nbytes()
        return totals

    def _publish_admission(self,entry,stats):
        p=self.policy["kv_cache"]
        for d,size in entry.bytes_by_device.items():
            if d!="cpu" and size>p["resident_entry_publish_cap_bytes_by_gpu"].get(d,0):return "resident_cap"
        for d,s in stats.items():
            if s["peak"]+p["initial_physical_headroom_bytes_by_gpu"].get(d,2*2**30)>s["usable"]:return "physical_headroom"
        return None

    def _sample(self,logits,temperature,top_p):
        t=self.torch
        if temperature==0:return int(logits.argmax(-1).item())
        scores,indices=t.sort(logits.float()/temperature,descending=True)
        probabilities=t.softmax(scores,-1)
        scores=scores.masked_fill(probabilities.cumsum(-1)-probabilities>top_p,-float("inf"))
        sample=t.multinomial(t.softmax(scores,-1),1)
        return int(indices.gather(-1,sample).item())

    def _execute(self,ids,output,temperature,top_p,previous=None):
        from transformers import DynamicCache
        t=self.torch
        now=time.monotonic()
        deadline=now+self.policy["queue"]["model_phase_deadline_seconds"]
        consumed=len(previous.token_ids) if previous else 0
        cache=previous.cache if previous else DynamicCache(config=self.model.config.get_text_config())
        logits=previous.next_logits if previous else None
        before=self._stats(reset=True)
        prompt_start=time.monotonic()
        chunks=0
        emitted=[]
        try:
            with t.inference_mode():
                chunk=self.policy["model_baseline"]["prefill_chunk_tokens"]
                for start in range(consumed,len(ids),chunk):
                    if time.monotonic()>deadline:raise CacheRuntimeError(504,"model_deadline","Model deadline exceeded")
                    end=min(start+chunk,len(ids))
                    input_ids=t.tensor([ids[start:end]],dtype=t.long,device=self.device)
                    mask=t.ones((1,end),dtype=t.long,device=self.device)
                    positions=t.arange(start,end,device=self.device).unsqueeze(0)
                    out=self.model(input_ids=input_ids,attention_mask=mask,position_ids=positions,
                                   past_key_values=cache,use_cache=True,logits_to_keep=1)
                    cache=out.past_key_values
                    logits=out.logits[:,-1,:].detach()
                    del out,input_ids,mask,positions
                    chunks+=1
                if logits is None:raise CacheRuntimeError(500,"missing_logits","Missing next-token state")
                self._sync()
                prefill_done=time.monotonic()
                first_token=None
                for i in range(output):
                    if time.monotonic()>deadline:raise CacheRuntimeError(504,"model_deadline","Model deadline exceeded")
                    token=self._sample(logits,temperature,top_p)
                    emitted.append(token)
                    if first_token is None:first_token=time.monotonic()
                    if token in self._eos:break
                    if i+1<output:
                        pos=len(ids)+i
                        input_ids=t.tensor([[token]],dtype=t.long,device=self.device)
                        mask=t.ones((1,pos+1),dtype=t.long,device=self.device)
                        positions=t.tensor([[pos]],dtype=t.long,device=self.device)
                        out=self.model(input_ids=input_ids,attention_mask=mask,position_ids=positions,
                                       past_key_values=cache,use_cache=True,logits_to_keep=1)
                        cache=out.past_key_values
                        logits=out.logits[:,-1,:].detach()
                        del out,input_ids,mask,positions
            self._sync()
            finished=time.monotonic()
            stats=self._stats()
            candidate=CacheEntry("","",0,0,"",self.fingerprint,list(ids)+emitted[:-1],cache,logits,
                                 previous.created_at if previous else finished,finished,self._unique_bytes(cache))
            expected=len(candidate.token_ids)
            for layer in getattr(cache,"layers",[]):
                if hasattr(layer,"get_seq_length") and int(layer.get_seq_length())!=expected:
                    raise CacheRuntimeError(500,"cache_position_mismatch","Logical cache positions do not match consumed tokens")
            return {"text":self.tokenizer.decode(emitted,skip_special_tokens=True),
                    "finish_reason":"stop" if emitted[-1] in self._eos else "length",
                    "prompt_tokens":len(ids),"completion_tokens":len(emitted),
                    "cache":{"hit":bool(previous),"reused_tokens":consumed,"suffix_tokens":len(ids)-consumed,
                             "consumed_tokens":expected,"published":False,"bytes_by_device":candidate.bytes_by_device},
                    "metrics":{"prefill_ms":(prefill_done-prompt_start)*1000,"ttft_ms":(first_token-now)*1000,
                               "decode_ms":(finished-first_token)*1000,"total_ms":(finished-now)*1000,
                               "output_tokens_per_second":max(0,len(emitted)-1)/max(finished-first_token,1e-9),
                               "prefill_chunks":chunks,"memory_before":before,"memory_after":stats},
                    "_candidate":candidate}
        except BaseException as exc:
            self.abort()
            try:self._sync()
            except Exception:pass
            cache=logits=previous=out=input_ids=mask=positions=candidate=None
            exc.__traceback__=None
            if isinstance(exc,t.cuda.OutOfMemoryError):
                gc.collect()
                t.cuda.empty_cache()
                raise CacheRuntimeError(503,"gpu_out_of_memory","GPU memory exhausted; cache invalidated") from None
            raise exc.with_traceback(None)

    def generate_session(self,messages,owner,session_id,revision,epoch,dependency_digest,max_tokens=256,temperature=0.0,top_p=1.0):
        ids=self.encode(messages)
        self._limits(ids,max_tokens,temperature,top_p)
        previous,reason=None,"empty"
        with self._state_lock:
            entry=self._entry
            if entry:
                if self._expired(entry,time.monotonic()):reason="ttl"
                elif (entry.owner,entry.session_id,entry.revision,entry.epoch,entry.dependency_digest,entry.fingerprint)!=(owner,session_id,revision,epoch,dependency_digest,self.fingerprint):reason="identity_or_revision"
                elif ids[:len(entry.token_ids)]!=entry.token_ids:reason="prefix"
                else:previous,reason=entry,"hit"
            self._entry=None
            self._inflight=previous
            self._last_reason=reason
        # A miss must release the old GPU entry before allocating a cold cache.
        entry=None
        try:
            result=self._execute(ids,max_tokens,temperature,top_p,previous)
        except BaseException:
            previous=None
            self.abort()
            raise
        result["_candidate"].owner=owner
        result["_candidate"].session_id=session_id
        result["cache"]["reason"]=reason
        self._inflight=result["_candidate"]
        return result

    def publish(self,result,revision,epoch,dependency_digest):
        candidate=result.pop("_candidate",None)
        if candidate is None:return False
        with self._state_lock:
            reason=self._publish_admission(candidate,result["metrics"]["memory_after"])
            if self._expired(candidate,time.monotonic()):reason="ttl"
            if reason:
                self._clear(reason)
                result["cache"].update(published=False,publish_reason=reason)
                return False
            candidate.revision,candidate.epoch,candidate.dependency_digest=revision,epoch,dependency_digest
            candidate.last_used=time.monotonic()
            self._entry=candidate
            self._inflight=None
            self._last_reason="ready"
            result["cache"].update(published=True,publish_reason="ready")
            return True

    def cache_status(self,owner,session_id):
        with self._state_lock:
            entry=self._entry
            if entry and self._expired(entry,time.monotonic()):
                self._clear("ttl")
                entry=None
            if not entry or (entry.owner,entry.session_id)!=(owner,session_id):return {"state":"EMPTY","reason":self._last_reason}
            p=self.policy["kv_cache"]
            return {"state":"READY","consumed_tokens":len(entry.token_ids),"revision":entry.revision,
                    "bytes_by_device":entry.bytes_by_device,
                    "idle_remaining_seconds":max(0,p["idle_ttl_seconds"]-(time.monotonic()-entry.last_used)),
                    "absolute_remaining_seconds":max(0,p["absolute_ttl_seconds"]-(time.monotonic()-entry.created_at))}

    def generate_stateless(self,messages,max_tokens=256,temperature=0.0,top_p=1.0):
        ids=self.encode(messages)
        self._limits(ids,max_tokens,temperature,top_p)
        self.abort()
        result=self._execute(ids,max_tokens,temperature,top_p)
        result.pop("_candidate",None)
        result["cache"]["reason"]="stateless"
        return result

    def calibrate_planner(self):
        seed=self.tokenizer("Calibration data. ",add_special_tokens=False)["input_ids"]
        ids=(seed*(2048//max(len(seed),1)+1))[:2048]
        result=self._execute(ids,8,0.0,1.0)
        self._planner_profile={d:max(0,s["peak"]-result["metrics"]["memory_before"][d]["allocated"]) for d,s in result["metrics"]["memory_after"].items()}
        result.pop("_candidate",None)
        self._last_reason="empty"
        return self._planner_profile

    def plan_memory(self,source_text,owner,session_id):
        system=('Extract only exact short factual spans explicitly written by the user. Return JSON only: '
                '{"facts":[{"text":"exact source substring","kind":"fact","start":0,"end":1}]}. '
                'Offsets are Python Unicode character offsets. Do not invent facts. Storage is pending until validation.')
        messages=[{"role":"system","content":system},{"role":"user","content":source_text}]
        ids=self.encode(messages)
        if len(ids)>self.policy["memory"]["planner_input_total_cap"]:return None
        stats=self._stats()
        if self._entry and (self._planner_profile is None or any(
            s["allocated"]+self._planner_profile.get(d,0)+512*2**20+self.policy["kv_cache"]["initial_physical_headroom_bytes_by_gpu"].get(d,2*2**30)>s["usable"]
            for d,s in stats.items())):return None
        result=self._execute(ids,self.policy["memory"]["planner_output_cap"],0.0,1.0)
        result.pop("_candidate",None)
        text=result["text"].strip()
        fence=chr(96)*3
        if text.startswith(fence):
            text=chr(10).join(text.splitlines()[1:]).rsplit(fence,1)[0]
        try:facts=json.loads(text).get("facts",[])
        except (ValueError,AttributeError):return []
        validated=[]
        if not isinstance(facts,list):return validated
        for fact in facts[:20]:
            if not isinstance(fact,dict):continue
            value,start,end=fact.get("text"),fact.get("start"),fact.get("end")
            if not isinstance(value,str) or not value:
                continue
            exact=(type(start) is int and type(end) is int and 0<=start<end<=len(source_text) and source_text[start:end]==value)
            if not exact:
                start=source_text.find(value)
                if start<0 or start!=source_text.rfind(value):
                    continue
                end=start+len(value)
            validated.append({"text":value,"kind":fact.get("kind","fact"),"start":start,"end":end})
        return validated
